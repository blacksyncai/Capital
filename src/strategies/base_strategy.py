# Configure logging
logger = logging.getLogger(__name__)


class StrategyError(Exception):
    """Strategy error."""
    pass


class StrategyStatus(str, Enum):
    """Strategy status enumeration."""
    IDLE = "IDLE"
    RUNNING = "RUNNING"
    PAUSED = "PAUSED"
    STOPPED = "STOPPED"
    ERROR = "ERROR"


@dataclass
class StrategyConfig:
    """Configuration for a strategy."""
    strategy_id: str
    name: str
    description: str = ""
    enabled: bool = True
    parameters: Dict[str, Any] = field(default_factory=dict)
    risk_overrides: Dict[str, Any] = field(default_factory=dict)


@dataclass
class TradeSignal:
    """Trade signal generated by a strategy."""
    signal_id: str
    strategy_id: str
    instrument: str
    action: str  # OPEN, CLOSE, HOLD
    direction: str  # BUY_SELL, SELL_BUY
    lot_size: float
    timestamp: datetime
    confidence: float = 1.0
    priority: int = 0
    metadata: Dict[str, Any] = field(default_factory=dict)


@dataclass
class StrategyResult:
    """Result of strategy execution."""
    strategy_id: str
    cycle_id: Optional[str] = None
    success: bool = True
    message: str = ""
    trade_signals: List[TradeSignal] = field(default_factory=list)
    errors: List[str] = field(default_factory=list)
    warnings: List[str] = field(default_factory=list)
    performance: Dict[str, float] = field(default_factory=dict)


class BaseStrategy(ABC):
    """
    Abstract base class for trading strategies.
    
    All strategies must inherit from this class and implement
    the required methods for signal generation and execution.
    """
    
    def __init__(self, strategy_id: str, config: Optional[StrategyConfig] = None):
        """
        Initialize the strategy.
        
        Args:
            strategy_id: Unique strategy identifier
            config: Strategy configuration
        """
        self.strategy_id = strategy_id
        self.config = config or self._get_default_config()
        self.logger = get_logger(f"strategy.{strategy_id}")
        
        # Dependencies
        self.order_manager = OrderManager()
        self.trade_state_manager = TradeStateManager()
        self.risk_engine = RiskEngine()
        
        # State
        self.status = StrategyStatus.IDLE
        self.running = False
        self.paused = False
        self.error = None
        
        # Performance tracking
        self.total_trades = 0
        self.winning_trades = 0
        self.losing_trades = 0
        self.total_pnl = 0.0
        self.max_drawdown = 0.0
        
        self._initialized = False
    
    def _get_default_config(self) -> StrategyConfig:
        """Get default configuration."""
        return StrategyConfig(
            strategy_id=self.strategy_id,
            name=self.__class__.__name__,
            description=self.__doc__ or "",
            enabled=True,
            parameters={},
            risk_overrides={}
        )
    
    def initialize(self) -> None:
        """Initialize the strategy."""
        if self._initialized:
            return
        
        self.order_manager.initialize()
        self.trade_state_manager.initialize()
        self.risk_engine.initialize()
        
        self._initialized = True
        self.logger.info(f"Strategy {self.strategy_id} initialized")
    
    def start(self) -> None:
        """Start the strategy."""
        if self.running:
            return
        
        self.initialize()
        self.running = True
        self.paused = False
        self.status = StrategyStatus.RUNNING
        
        self.logger.info(f"Strategy {self.strategy_id} started")
    
    def stop(self) -> None:
        """Stop the strategy."""
        self.running = False
        self.status = StrategyStatus.STOPPED
        
        # Close all active cycles
        active_cycles = self.trade_state_manager.get_active_cycles()
        for cycle_id, state in active_cycles.items():
            if state.strategy_id == self.strategy_id:
                try:
                    self.trade_state_manager.close_cycle(
                        cycle_id,
                        reason="strategy_stopped",
                        comment=f"Strategy {self.strategy_id} stopped"
                    )
                except Exception as e:
                    self.logger.error(f"Error closing cycle {cycle_id}: {e}")
        
        self.logger.info(f"Strategy {self.strategy_id} stopped")
    
    def pause(self) -> None:
        """Pause the strategy."""
        self.paused = True
        self.status = StrategyStatus.PAUSED
        self.logger.info(f"Strategy {self.strategy_id} paused")
    
    def resume(self) -> None:
        """Resume the strategy."""
        self.paused = False
        self.status = StrategyStatus.RUNNING
        self.logger.info(f"Strategy {self.strategy_id} resumed")
    
    @abstractmethod
    def generate_signal(self, context: Dict[str, Any]) -> Optional[TradeSignal]:
        """
        Generate a trade signal.
        
        Args:
            context: Context dictionary with market data, etc.
            
        Returns:
            TradeSignal or None if no signal
        """
        pass
    
    @abstractmethod
    def should_close_cycle(self, cycle_id: str, context: Dict[str, Any]) -> Tuple[bool, str]:
        """
        Determine if a cycle should be closed.
        
        Args:
            cycle_id: Cycle ID
            context: Context dictionary
            
        Returns:
            Tuple of (should_close, reason)
        """
        pass
    
    def execute_signal(self, signal: TradeSignal) -> StrategyResult:
        """
        Execute a trade signal.
        
        Args:
            signal: Trade signal
            
        Returns:
            StrategyResult
        """
        result = StrategyResult(
            strategy_id=self.strategy_id,
            success=False
        )
        
        try:
            # Check if trading is allowed
            can_trade, reasons = self.risk_engine.can_trade()
            if not can_trade:
                result.success = False
                result.message = f"Trading blocked: {', '.join(reasons)}"
                return result
            
            # Check pre-trade risk
            pre_check = self.risk_engine.check_before_trade(
                instrument=signal.instrument,
                lot_size=signal.lot_size,
                direction=signal.direction
            )
            
            if not pre_check.passed:
                result.success = False
                result.message = f"Pre-trade check failed: {pre_check.violation.message if pre_check.violation else 'Unknown'}"
                return result
            
            # Execute the signal
            if signal.action == "OPEN":
                cycle_id = self.trade_state_manager.create_cycle(
                    instrument=signal.instrument,
                    lot_size=signal.lot_size,
                    direction=signal.direction,
                    strategy_id=self.strategy_id,
                    comment=f"Signal: {signal.signal_id}"
                )
                
                # Open the cycle
                self.trade_state_manager.open_cycle(cycle_id)
                
                result.success = True
                result.cycle_id = cycle_id
                result.message = f"Cycle opened: {cycle_id}"
                
            elif signal.action == "CLOSE":
                # Find active cycles for this strategy
                active_cycles = self.trade_state_manager.get_active_cycles()
                for cycle_id, state in active_cycles.items():
                    if state.strategy_id == self.strategy_id:
                        self.trade_state_manager.close_cycle(
                            cycle_id,
                            reason="strategy_signal",
                            comment=f"Signal: {signal.signal_id}"
                        )
                        result.success = True
                        result.cycle_id = cycle_id
                        result.message = f"Cycle closed: {cycle_id}"
                        break
            
        except Exception as e:
            result.success = False
            result.message = str(e)
            result.errors.append(str(e))
            self.logger.error(f"Error executing signal {signal.signal_id}: {e}")
        
        return result
    
    def monitor_cycles(self, context: Dict[str, Any]) -> List[StrategyResult]:
        """
        Monitor active cycles and close them if needed.
        
        Args:
            context: Context dictionary
            
        Returns:
            List of StrategyResult for closed cycles
        """
        results = []
        
        active_cycles = self.trade_state_manager.get_active_cycles()
        
        for cycle_id, state in active_cycles.items():
            if state.strategy_id != self.strategy_id:
                continue
            
            should_close, reason = self.should_close_cycle(cycle_id, context)
            
            if should_close:
                try:
                    self.trade_state_manager.close_cycle(
                        cycle_id,
                        reason=reason,
                        comment=f"Strategy {self.strategy_id} monitoring"
                    )
                    results.append(StrategyResult(
                        strategy_id=self.strategy_id,
                        cycle_id=cycle_id,
                        success=True,
                        message=f"Cycle closed by monitor: {reason}"
                    ))
                except Exception as e:
                    results.append(StrategyResult(
                        strategy_id=self.strategy_id,
                        cycle_id=cycle_id,
                        success=False,
                        message=str(e),
                        errors=[str(e)]
                    ))
        
        return results
    
    def run(self, context: Dict[str, Any]) -> StrategyResult:
        """
        Run one iteration of the strategy.
        
        Args:
            context: Context dictionary
            
        Returns:
            StrategyResult
        """
        result = StrategyResult(strategy_id=self.strategy_id)
        
        if not self.running or self.paused:
            result.message = "Strategy not running or paused"
            return result
        
        try:
            # Generate signal
            signal = self.generate_signal(context)
            
            if signal:
                result.trade_signals.append(signal)
                
                # Execute signal
                exec_result = self.execute_signal(signal)
                result.success = exec_result.success
                result.cycle_id = exec_result.cycle_id
                result.message = exec_result.message
                result.errors.extend(exec_result.errors)
            
            # Monitor cycles
            monitor_results = self.monitor_cycles(context)
            result.success = result.success and all(r.success for r in monitor_results)
            
        except Exception as e:
            result.success = False
            result.message = str(e)
            result.errors.append(str(e))
            self.logger.error(f"Error in strategy {self.strategy_id}: {e}")
        
        return result
    
    def get_status(self) -> Dict[str, Any]:
        """
        Get the current status of the strategy.
        
        Returns:
            Status dictionary
        """
        return {
            "strategy_id": self.strategy_id,
            "name": self.config.name,
            "status": self.status.value,
            "running": self.running,
            "paused": self.paused,
            "total_trades": self.total_trades,
            "winning_trades": self.winning_trades,
            "losing_trades": self.losing_trades,
            "total_pnl": self.total_pnl,
            "max_drawdown": self.max_drawdown,
            "win_rate": self.winning_trades / self.total_trades if self.total_trades > 0 else 0,
            "error": self.error
        }
    
    def get_performance(self) -> Dict[str, float]:
        """
        Get performance metrics.
        
        Returns:
            Performance dictionary
        """
        return {
            "total_trades": self.total_trades,
            "winning_trades": self.winning_trades,
            "losing_trades": self.losing_trades,
            "total_pnl": self.total_pnl,
            "max_drawdown": self.max_drawdown,
            "win_rate": self.winning_trades / self.total_trades if self.total_trades > 0 else 0,
            "profit_factor": (self.winning_trades / self.losing_trades) if self.losing_trades > 0 else float('inf'),
            "avg_win": self.total_pnl / self.winning_trades if self.winning_trades > 0 else 0,
            "avg_loss": self.total_pnl / self.losing_trades if self.losing_trades > 0 else 0
        }
    
    def reset_performance(self) -> None:
        """Reset performance metrics."""
        self.total_trades = 0
        self.winning_trades = 0
        self.losing_trades = 0
        self.total_pnl = 0.0
        self.max_drawdown = 0.0
    
    def _create_signal(
        self,
        action: str,
        instrument: str,
        direction: str,
        lot_size: float,
        confidence: float = 1.0,
        priority: int = 0,
        metadata: Optional[Dict[str, Any]] = None
    ) -> TradeSignal:
        """
        Create a trade signal.
        
        Args:
            action: Signal action (OPEN, CLOSE, HOLD)
            instrument: Trading instrument
            direction: Trade direction
            lot_size: Lot size
            confidence: Signal confidence (0-1)
            priority: Signal priority
            metadata: Additional metadata
            
        Returns:
            TradeSignal
        """
        return TradeSignal(
            signal_id=f"sig_{self.strategy_id}_{uuid.uuid4().hex[:8]}",
            strategy_id=self.strategy_id,
            instrument=instrument,
            action=action,
            direction=direction,
            lot_size=lot_size,
            timestamp=datetime.utcnow(),
            confidence=confidence,
            priority=priority,
            metadata=metadata or {}
        )


# Strategy factory
_strategies: Dict[str, BaseStrategy] = {}


def get_strategy(strategy_id: str, config: Optional[StrategyConfig] = None) -> BaseStrategy:
    """
    Get or create a strategy instance.
    
    Args:
        strategy_id: Strategy identifier
        config: Optional configuration
        
    Returns:
        Strategy instance
    """
    if strategy_id not in _strategies:
        # Import dynamically
        module_name = strategy_id.lower().replace("_", "")
        try:
            module = __import__(f"..{module_name}", fromlist=[strategy_id])
            strategy_class = getattr(module, strategy_id)
            _strategies[strategy_id] = strategy_class(strategy_id, config)
        except ImportError as e:
            raise StrategyError(f"Cannot import strategy module for {strategy_id}: {e}")
    
    return _strategies[strategy_id]


def reset_strategies() -> None:
    """Reset all strategy instances."""
    global _strategies
    for strategy in _strategies.values():
        strategy.stop()
    _strategies.clear()
